const dictionaries: Record<Locale, Dictionary> = { en, id };
const intlLocales: Record<Locale, string> = { en: 'en-US', id: 'id-ID' };

export function isLocale(locale: string | null | undefined): locale is Locale {
	return locales.some((item) => item.code === locale);
}

export function resolveLocale(value: string | null | undefined): Locale {
	if (isLocale(value)) return value;
	const primary = value?.split(',')[0]?.split('-')[0];
	return isLocale(primary) ? primary : 'en';
}

export function createTranslator(locale: Locale) {
	const dictionary = dictionaries[locale] ?? dictionaries.en;
	return (key: string, params?: Record<string, string | number>) => {
		let text = dictionary[key] ?? dictionaries.en[key] ?? key;
		if (params) {
			for (const [paramKey, paramVal] of Object.entries(params)) {
				text = text.replaceAll(`{${paramKey}}`, String(paramVal));
			}
		}
		return text;
	};
}

export function formatDate(
	value: Date | string | number,
	locale: Locale,
	options: Intl.DateTimeFormatOptions = { dateStyle: 'medium' }
) {
	return new Intl.DateTimeFormat(intlLocales[locale], options).format(new Date(value));
}

export function formatNumber(value: number, locale: Locale, options?: Intl.NumberFormatOptions) {
	return new Intl.NumberFormat(intlLocales[locale], options).format(value);
}

export function formatCurrency(value: number | null | undefined, locale: Locale, currency = locale === 'id' ? 'IDR' : 'USD') {
	if (value === null || value === undefined || !Number.isFinite(value)) return '-';
	return formatNumber(value, locale, { style: 'currency', currency });
}

export function formatRelativeTime(value: number, unit: Intl.RelativeTimeFormatUnit, locale: Locale) {
	return new Intl.RelativeTimeFormat(intlLocales[locale], { numeric: 'auto' }).format(value, unit);
}

export function resolveTerminology(
	terminology: { en: Record<string, string>; id: Record<string, string> } | null | undefined,
	locale: Locale
) {
	const fallback =
		locale === 'id'
			? {
					assetSingular: 'Perangkat',
					assetPlural: 'Perangkat',
					ticketSingular: 'Tiket Servis',
					ticketPlural: 'Tiket Servis',
					requesterSingular: 'Pelanggan',
					requesterPlural: 'Pelanggan',
					primaryIdentifierLabel: 'Nomor Seri',
					secondaryIdentifierLabel: 'Label Aset',
					meterLabel: 'Meter Pemakaian'
				}
			: {
					assetSingular: 'Device',
					assetPlural: 'Devices',
					ticketSingular: 'Service Ticket',
					ticketPlural: 'Service Tickets',
					requesterSingular: 'Customer',
					requesterPlural: 'Customers',
					primaryIdentifierLabel: 'Serial Number',
					secondaryIdentifierLabel: 'Asset Label',
					meterLabel: 'Usage Meter'
				};

	if (!terminology) return fallback;
	return { ...fallback, ...(terminology[locale] ?? terminology.en) };
}

